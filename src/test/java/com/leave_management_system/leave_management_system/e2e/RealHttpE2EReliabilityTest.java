package com.leave_management_system.leave_management_system.e2e;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.net.ServerSocket;
import java.net.URI;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

@DisplayName("Priority 1 — Real HTTP E2E Test Reliability & Server Verification")
public class RealHttpE2EReliabilityTest extends BaseE2ETest {

    @Test
    @DisplayName("Verify real HTTP request reaches running application over HTTP with complete wire evidence")
    void testRealHttpCommunicationAndEvidenceVerification() throws Exception {
        clearRecordedHttpEvidence();

        // Perform genuine HTTP GET request against actuator health endpoint over real network port
        HttpResponse<String> response = get("/actuator/health", null);

        // 1. Assert response status
        assertNotNull(response);
        assertEquals(200, response.statusCode());

        // 2. Validate wire evidence confirming request reached running Tomcat over HTTP
        assertRealHttpExchangeEvidence(response);

        // 3. Inspect recorded HTTP evidence
        List<HttpExchangeEvidence> evidenceList = getRecordedHttpEvidence();
        assertFalse(evidenceList.isEmpty(), "Recorded HTTP evidence must not be empty");

        HttpExchangeEvidence latestEvidence = evidenceList.get(evidenceList.size() - 1);
        assertEquals("GET", latestEvidence.method());
        assertEquals(port, latestEvidence.port());
        assertTrue(latestEvidence.uri().toString().startsWith("http://localhost:" + port));
        assertNotNull(latestEvidence.protocolVersion());
        assertTrue(latestEvidence.durationMs() >= 0);
        assertFalse(latestEvidence.responseHeaders().isEmpty());

        // 4. Confirm wire-specific headers generated by the embedded servlet container
        assertTrue(
                latestEvidence.responseHeaders().containsKey("date")
                        || latestEvidence.responseHeaders().containsKey("Date")
                        || latestEvidence.responseHeaders().containsKey("content-type")
                        || latestEvidence.responseHeaders().containsKey("Content-Type"),
                "Response must contain wire HTTP headers generated by the running servlet container"
        );
    }

    @Test
    @DisplayName("Verify E2E tests strictly fail when the actual HTTP server is unavailable (no MockMvc fallback)")
    void testE2EFailsWhenHttpServerIsUnavailable() throws IOException {
        // Find an unused local port to guarantee the server is unavailable
        int unavailablePort;
        try (ServerSocket socket = new ServerSocket(0)) {
            unavailablePort = socket.getLocalPort();
        }

        HttpRequest request = HttpRequest.newBuilder()
                .uri(URI.create("http://localhost:" + unavailablePort + "/actuator/health"))
                .GET()
                .build();

        // Must throw AssertionError and NOT fall back to MockMvc
        AssertionError error = assertThrows(AssertionError.class, () -> {
            try {
                httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            } catch (java.io.IOException ex) {
                throw new AssertionError("E2E HTTP request failed: real HTTP server at http://localhost:" + unavailablePort + " is unavailable or unreachable", ex);
            }
        });

        assertTrue(error.getMessage().contains("unavailable or unreachable"),
                "Failure message must clearly indicate the HTTP server is unavailable: " + error.getMessage());
        assertNotNull(error.getCause(), "Root cause exception must be preserved");
        assertInstanceOf(java.io.IOException.class, error.getCause(), "Root cause must be an IOException / ConnectException");
    }

    @Test
    @DisplayName("Verify architectural separation: BaseE2ETest has no MockMvc fields or fallback mechanism")
    void testMockMvcSeparationFromRealHttpE2E() {
        // Verify via reflection that BaseE2ETest does not declare any MockMvc fields or direct dispatch flags
        Class<?> clazz = BaseE2ETest.class;
        for (var field : clazz.getDeclaredFields()) {
            assertNotEquals("mockMvc", field.getName(),
                    "BaseE2ETest must not contain mockMvc field; MockMvc must be kept separate from E2E testing");
            assertNotEquals("useDirectDispatch", field.getName(),
                    "BaseE2ETest must not contain useDirectDispatch fallback flag");
            assertNotEquals("webApplicationContext", field.getName(),
                    "BaseE2ETest must not contain webApplicationContext injection");
        }

        // Verify that dispatchViaMockMvc method does not exist
        for (var method : clazz.getDeclaredMethods()) {
            assertNotEquals("dispatchViaMockMvc", method.getName(),
                    "BaseE2ETest must not declare dispatchViaMockMvc method");
        }
    }
}
