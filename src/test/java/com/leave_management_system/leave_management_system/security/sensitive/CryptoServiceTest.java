package com.leave_management_system.leave_management_system.security.sensitive;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import javax.crypto.Cipher;
import javax.crypto.SecretKey;
import javax.crypto.spec.GCMParameterSpec;
import javax.crypto.spec.SecretKeySpec;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.SecureRandom;
import java.util.Base64;

import static org.junit.jupiter.api.Assertions.*;

public class CryptoServiceTest {

    private CryptoService cryptoService;
    private static final String TEST_KEY = "my-secure-32-byte-test-key-for-aes-256";

    @BeforeEach
    void setUp() {
        cryptoService = new CryptoService(TEST_KEY);
    }

    @Test
    @DisplayName("encrypt and decrypt: round trip restores original plaintext")
    void encryptAndDecrypt_RoundTrip_Success() {
        String plaintext = "SuperSensitiveData!@#123";

        String ciphertext = cryptoService.encrypt(plaintext);
        assertNotNull(ciphertext);
        assertTrue(ciphertext.startsWith(CryptoService.ENCRYPTION_PREFIX));
        assertNotEquals(plaintext, ciphertext);

        String decrypted = cryptoService.decrypt(ciphertext);
        assertEquals(plaintext, decrypted);
    }

    @Test
    @DisplayName("Backward compatibility: decrypts ciphertext generated by the previous implementation")
    void decrypt_CiphertextGeneratedByPreviousImplementation_Success() throws Exception {
        // A Base64-encoded 256-bit key where raw UTF-8 SHA-256 is distinct from Base64-decoded SHA-256
        String base64Key = "c2VjdXJlUmFuZG9tSldUU2VjcmV0S2V5MjAyNkZvckxlYXZlTWFuYWdlbWVudFN5c3RlbSE=";
        String plaintext = "SensitivePersonalRecord-SSN-999-88-7777";

        // Generate ciphertext using the PREVIOUS implementation's derivation:
        // sha.digest(secret.getBytes(StandardCharsets.UTF_8))
        MessageDigest sha = MessageDigest.getInstance("SHA-256");
        byte[] legacyKeyBytes = sha.digest(base64Key.getBytes(StandardCharsets.UTF_8));
        SecretKey legacyKey = new SecretKeySpec(legacyKeyBytes, "AES");

        byte[] iv = new byte[12];
        new SecureRandom().nextBytes(iv);
        Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
        cipher.init(Cipher.ENCRYPT_MODE, legacyKey, new GCMParameterSpec(128, iv));
        byte[] encryptedBytes = cipher.doFinal(plaintext.getBytes(StandardCharsets.UTF_8));

        ByteBuffer buf = ByteBuffer.allocate(iv.length + encryptedBytes.length);
        buf.put(iv);
        buf.put(encryptedBytes);
        String legacyCiphertext = CryptoService.ENCRYPTION_PREFIX + Base64.getEncoder().encodeToString(buf.array());

        // Initialize modern CryptoService with this key
        CryptoService modernService = new CryptoService(base64Key);

        // Modern service must successfully decrypt the legacy ciphertext using its fallback mechanism
        String decrypted = modernService.decrypt(legacyCiphertext);
        assertEquals(plaintext, decrypted, "Modern CryptoService must decrypt records encrypted by the previous implementation");
    }

    @Test
    @DisplayName("Key Rotation: decrypts ciphertext encrypted with rotated previous key")
    void keyRotation_DecryptsWithPreviousKey() {
        String oldKey = "old-secure-encryption-key-32-chars-long!";
        String newKey = "new-secure-encryption-key-32-chars-long!";
        String plaintext = "SensitiveSalaryData-$150000";

        CryptoService oldService = new CryptoService(oldKey);
        String ciphertextUnderOldKey = oldService.encrypt(plaintext);

        // New service initialized with newKey as primary and oldKey in previous-keys
        CryptoService rotatedService = new CryptoService(newKey, oldKey);

        // Must successfully decrypt ciphertext encrypted under the old key
        String decrypted = rotatedService.decrypt(ciphertextUnderOldKey);
        assertEquals(plaintext, decrypted, "Rotated service must decrypt data from previous keys");

        // Safe migration: rotateCiphertext re-encrypts under the new key
        String migratedCiphertext = rotatedService.rotateCiphertext(ciphertextUnderOldKey);
        assertNotNull(migratedCiphertext);

        // Verify the migrated ciphertext is decryptable by a service having ONLY the new key
        CryptoService newOnlyService = new CryptoService(newKey);
        assertEquals(plaintext, newOnlyService.decrypt(migratedCiphertext), "Migrated ciphertext must be encrypted with the new primary key");
    }

    @Test
    @DisplayName("encrypt: null input returns null")
    void encrypt_Null_ReturnsNull() {
        assertNull(cryptoService.encrypt(null));
    }

    @Test
    @DisplayName("decrypt: null input returns null")
    void decrypt_Null_ReturnsNull() {
        assertNull(cryptoService.decrypt(null));
    }

    @Test
    @DisplayName("decrypt: legacy unencrypted data returns as-is")
    void decrypt_LegacyUnencrypted_ReturnsAsIs() {
        String unencrypted = "plain-unencrypted-legacy-string";

        String result = cryptoService.decrypt(unencrypted);
        assertEquals(unencrypted, result);
    }

    @Test
    @DisplayName("decrypt: tampered ciphertext throws SecurityException")
    void decrypt_TamperedCiphertext_ThrowsSecurityException() {
        String encrypted = cryptoService.encrypt("Sensitive Information");
        // Tamper with payload characters
        String tampered = encrypted.substring(0, encrypted.length() - 4) + "AAAA";

        assertThrows(SecurityException.class, () -> cryptoService.decrypt(tampered));
    }

    @Test
    @DisplayName("isEncrypted: returns true only for strings starting with ENC:")
    void isEncrypted_ChecksPrefix() {
        assertTrue(cryptoService.isEncrypted("ENC:dGVzdA=="));
        assertFalse(cryptoService.isEncrypted("dGVzdA=="));
        assertFalse(cryptoService.isEncrypted(null));
    }

    @Test
    @DisplayName("generateHmacBlindIndex: returns deterministic HMAC-SHA256 hex string")
    void generateHmacBlindIndex_Deterministic() {
        String input1 = "user@example.com";
        String input2 = " USER@EXAMPLE.COM "; // differing whitespace and case

        String hmac1 = cryptoService.generateHmacBlindIndex(input1);
        String hmac2 = cryptoService.generateHmacBlindIndex(input2);

        assertNotNull(hmac1);
        assertEquals(hmac1, hmac2, "Normalized input must produce identical blind index");
        assertNull(cryptoService.generateHmacBlindIndex(null));
    }
}
