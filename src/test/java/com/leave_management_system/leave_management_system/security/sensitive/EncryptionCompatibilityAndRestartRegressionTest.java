    /**
     * Helper method reproducing the PREVIOUS implementation's key derivation and encryption routine.
     */
    private String generateCiphertextWithPreviousImplementation(String secretKeyStr, String plaintext) throws Exception {
        MessageDigest sha = MessageDigest.getInstance("SHA-256");
        byte[] legacyKeyBytes = sha.digest(secretKeyStr.trim().getBytes(StandardCharsets.UTF_8));
        SecretKey legacyKey = new SecretKeySpec(legacyKeyBytes, "AES");

        byte[] iv = new byte[12];
        new SecureRandom().nextBytes(iv);

        Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
        cipher.init(Cipher.ENCRYPT_MODE, legacyKey, new GCMParameterSpec(128, iv));
        byte[] ciphertextWithTag = cipher.doFinal(plaintext.getBytes(StandardCharsets.UTF_8));

        ByteBuffer buf = ByteBuffer.allocate(iv.length + ciphertextWithTag.length);
        buf.put(iv);
        buf.put(ciphertextWithTag);

        return CryptoService.ENCRYPTION_PREFIX + Base64.getEncoder().encodeToString(buf.array());
    }

    @Test
    @DisplayName("Regression 1: Decrypts static historic ciphertext vector produced by the previous implementation")
    void test1_DecryptStaticHistoricCiphertextVector_Success() {
        // Initialize modern CryptoService with the previous implementation's key
        CryptoService modernService = new CryptoService(PREVIOUS_IMPL_KEY);

        String decrypted = modernService.decrypt(STATIC_HISTORIC_CIPHERTEXT);

        assertNotNull(decrypted, "Decrypted plaintext must not be null");
        assertEquals(STATIC_HISTORIC_PLAINTEXT, decrypted,
                "Modern CryptoService must successfully decrypt static historic ciphertext vector generated by the previous implementation");
        log.info("[REGRESSION 1 SUCCESS] Static historic ciphertext from previous implementation decrypted cleanly.");
    }

    @Test
    @DisplayName("Regression 2: Decrypts dynamically generated previous-implementation ciphertexts across various payload structures")
    void test2_DecryptDynamicPreviousImplementationCiphertexts_Success() throws Exception {
        CryptoService modernService = new CryptoService(PREVIOUS_IMPL_KEY);

        String[] testPayloads = {
                "Phone: +1-555-0199-RESTRICTED-DEV",
                "{\"employeeId\":101,\"baseSalary\":165000.00,\"currency\":\"USD\",\"equity\":2500}",
                "CompensationReview: APPROVED by Director (Sophia Vance) on 2026-11-13; Adjustment=+8.5%",
                "SimpleShortSecret"
        };

        for (String plaintext : testPayloads) {
            String legacyCiphertext = generateCiphertextWithPreviousImplementation(PREVIOUS_IMPL_KEY, plaintext);
            assertNotNull(legacyCiphertext);
            assertTrue(legacyCiphertext.startsWith(CryptoService.ENCRYPTION_PREFIX));

            String decrypted = modernService.decrypt(legacyCiphertext);
            assertEquals(plaintext, decrypted,
                    "Modern CryptoService must decrypt dynamic legacy ciphertext for payload: " + plaintext);
        }
        log.info("[REGRESSION 2 SUCCESS] Multi-payload dynamic ciphertexts from previous implementation decrypted cleanly.");
    }

    @Test
    @DisplayName("Regression 3: Key Rotation - Decrypts previous-implementation ciphertext under rotated keys and migrates to new key")
    void test3_VerifyKeyRotationAndCiphertextMigration() throws Exception {
        String newKey = "new-master-encryption-key-for-rotation-32-chars-long!";
        String payload = "ExecutiveCompensationPlan_DirectorTier_Salary=$240,000;BonusTarget=30%";

        // 1. Generate ciphertext using previous implementation under PREVIOUS_IMPL_KEY
        String legacyCiphertext = generateCiphertextWithPreviousImplementation(PREVIOUS_IMPL_KEY, payload);

        // 2. Initialize rotated service with newKey as primary and PREVIOUS_IMPL_KEY in previous-keys
        CryptoService rotatedService = new CryptoService(newKey, PREVIOUS_IMPL_KEY);

        // 3. Verify decryption of the legacy ciphertext using the rotated service
        String decryptedUnderRotated = rotatedService.decrypt(legacyCiphertext);
        assertEquals(payload, decryptedUnderRotated,
                "Rotated service must decrypt legacy ciphertext via fallback key registration");

        // 4. Migrate the ciphertext to the new primary key using rotateCiphertext()
        String migratedCiphertext = rotatedService.rotateCiphertext(legacyCiphertext);
        assertNotNull(migratedCiphertext);
        assertTrue(migratedCiphertext.startsWith(CryptoService.ENCRYPTION_PREFIX));
        assertNotEquals(legacyCiphertext, migratedCiphertext,
                "Migrated ciphertext must be re-encrypted with a new random IV and primary key");

        // 5. Verify the migrated ciphertext is decryptable by a service instance having ONLY the new key
        CryptoService newOnlyService = new CryptoService(newKey);
        String finalDecrypted = newOnlyService.decrypt(migratedCiphertext);
        assertEquals(payload, finalDecrypted,
                "Migrated ciphertext must be fully decryptable using ONLY the new primary key");

        // 6. Confirm that the service with only newKey CANNOT decrypt the old un-migrated legacy ciphertext
        assertThrows(SecurityException.class, () -> newOnlyService.decrypt(legacyCiphertext),
                "Service having only new key must reject un-migrated legacy ciphertext when previous key is not registered");

        log.info("[REGRESSION 3 SUCCESS] Key rotation and ciphertext migration verified with cryptographic isolation.");
    }

    @Test
    @DisplayName("Regression 4: Application Restart Lifecycle - Decrypts legacy records across multi-stage application restarts")
    void test4_VerifySuccessfulDecryptionAfterApplicationRestart() throws Exception {
        String keyV1 = PREVIOUS_IMPL_KEY;
        String keyV2 = "new-rotated-production-secret-key-32-bytes-v2!";
        String keyV3 = "final-generation-master-encryption-key-32-bytes-v3!";
        String sensitiveData = "ConfidentialAuditTrail_AccountUnlockedByAdmin_IP=192.168.1.50";

        // Generate ciphertext using previous implementation under keyV1
        String legacyCiphertext = generateCiphertextWithPreviousImplementation(keyV1, sensitiveData);

        // ---------------------------------------------------------------------------------
        // Application Lifecycle 1: Application running on Key V1 (previous implementation)
        // ---------------------------------------------------------------------------------
        ApplicationContextRunner appRunnerV1 = new ApplicationContextRunner()
                .withPropertyValues(
                        "app.security.encryption.key=" + keyV1,
                        "app.security.encryption.previous-keys="
                )
                .withUserConfiguration(CryptoService.class, AppProperties.class);

        appRunnerV1.run(contextV1 -> {
            CryptoService serviceV1 = contextV1.getBean(CryptoService.class);
            assertThat(serviceV1).isNotNull();
            String decrypted = serviceV1.decrypt(legacyCiphertext);
            assertEquals(sensitiveData, decrypted, "App V1 must decrypt its own legacy ciphertext");
            log.info("  -> [LIFECYCLE 1 OK] App V1 booted and verified decryption.");
        });

        // ---------------------------------------------------------------------------------
        // Application Lifecycle 2: Application RESTART with Rotated Key V2 + Key V1 fallback
        // ---------------------------------------------------------------------------------
        final String[] migratedHolder = new String[1];
        ApplicationContextRunner appRunnerV2 = new ApplicationContextRunner()
                .withPropertyValues(
                        "app.security.encryption.key=" + keyV2,
                        "app.security.encryption.previous-keys=" + keyV1
                )
                .withUserConfiguration(CryptoService.class, AppProperties.class);

        appRunnerV2.run(contextV2 -> {
            CryptoService serviceV2 = contextV2.getBean(CryptoService.class);
            assertThat(serviceV2).isNotNull();

            // Decrypt legacy ciphertext generated in Lifecycle 1 after application restart
            String decryptedAfterRestart = serviceV2.decrypt(legacyCiphertext);
            assertEquals(sensitiveData, decryptedAfterRestart,
                    "App V2 after restart must successfully decrypt legacy ciphertext from App V1");

            // Perform key rotation in the restarted application
            migratedHolder[0] = serviceV2.rotateCiphertext(legacyCiphertext);
            assertNotNull(migratedHolder[0]);
            log.info("  -> [LIFECYCLE 2 OK] App V2 restarted: legacy record decrypted and rotated.");
        });

        // ---------------------------------------------------------------------------------
        // Application Lifecycle 3: Application RESTART with Rotated Key V3 + Key V2 fallback
        // (Key V1 retired; migrated record re-encrypted under V2 must still decrypt in V3)
        // ---------------------------------------------------------------------------------
        ApplicationContextRunner appRunnerV3 = new ApplicationContextRunner()
                .withPropertyValues(
                        "app.security.encryption.key=" + keyV3,
                        "app.security.encryption.previous-keys=" + keyV2
                )
                .withUserConfiguration(CryptoService.class, AppProperties.class);

        appRunnerV3.run(contextV3 -> {
            CryptoService serviceV3 = contextV3.getBean(CryptoService.class);
            assertThat(serviceV3).isNotNull();

            // The migrated record (now under keyV2) must decrypt in restarted App V3 via keyV2 fallback
            String decryptedInV3 = serviceV3.decrypt(migratedHolder[0]);
            assertEquals(sensitiveData, decryptedInV3,
                    "App V3 after second restart must decrypt record migrated under Key V2");

            // Key V1 is now retired and not in previous-keys of V3: legacy ciphertext must be rejected
            assertThrows(SecurityException.class, () -> serviceV3.decrypt(legacyCiphertext),
                    "App V3 must reject un-migrated Key V1 ciphertext once Key V1 is retired from previous-keys");
            log.info("  -> [LIFECYCLE 3 OK] App V3 restarted: Key V2 fallback confirmed, Key V1 retirement enforced.");
        });

        log.info("[REGRESSION 4 SUCCESS] Multi-stage application restart lifecycle verified successfully.");
    }

    @Test
    @DisplayName("Regression 5: Database Persistence & Relational Querying across Application Restarts")
    void test5_VerifyDatabasePersistenceAcrossRestarts() throws Exception {
        String sensitivePayload = "ConfidentialAuditPayload: Admin override performed on leave_request_id=402";

        // 1. Generate ciphertext with previous implementation
        String legacyCiphertext = generateCiphertextWithPreviousImplementation(PREVIOUS_IMPL_KEY, sensitivePayload);

        // 2. Persist to relational database via AuditLog entity
        AuditLog auditLog = new AuditLog();
        auditLog.setAction("ADMIN_COMPENSATION_OVERRIDE");
        auditLog.setEntityType("COMPENSATION");
        auditLog.setEntityId(402L);
        auditLog.setOldValue("LegacyUnencryptedPlaceholder");
        auditLog.setNewValue(legacyCiphertext);
        auditLog.setIpAddress("127.0.0.1");
        auditLog.setTimestamp(LocalDateTime.now());

        AuditLog saved = auditLogRepository.saveAndFlush(auditLog);
        Long recordId = saved.getId();
        assertNotNull(recordId);

        // 3. Raw JDBC inspection: verify column on disk contains the exact ENC: ciphertext
        String rawDbValue = jdbcTemplate.queryForObject(
                "SELECT new_value FROM audit_logs WHERE id = ?", String.class, recordId);
        assertNotNull(rawDbValue);
        assertTrue(rawDbValue.startsWith(CryptoService.ENCRYPTION_PREFIX), "Raw DB column must store ENC: prefixed ciphertext");
        assertEquals(legacyCiphertext, rawDbValue, "Raw DB value must match persisted legacy ciphertext byte-for-byte");

        // 4. Simulate application restart with new rotated key + previous key
        String newKey = "brand-new-master-key-for-db-restart-test-32-chars!";
        CryptoService restartedService = new CryptoService(newKey, PREVIOUS_IMPL_KEY);

        // 5. Read back from database and decrypt using restarted service
        AuditLog retrieved = auditLogRepository.findById(recordId).orElseThrow();
        String decryptedFromDb = restartedService.decrypt(retrieved.getNewValue());
        assertEquals(sensitivePayload, decryptedFromDb,
                "Restored entity from database must decrypt cleanly using restarted service");

        // 6. Perform in-place key rotation in database
        retrieved.setNewValue(restartedService.rotateCiphertext(retrieved.getNewValue()));
        auditLogRepository.saveAndFlush(retrieved);

        // 7. Verify post-rotation: readable by a service having ONLY the new key
        CryptoService newOnlyService = new CryptoService(newKey);
        AuditLog updatedRecord = auditLogRepository.findById(recordId).orElseThrow();
        String finalDecrypted = newOnlyService.decrypt(updatedRecord.getNewValue());
        assertEquals(sensitivePayload, finalDecrypted,
                "Rotated database record must decrypt using only the new primary key");

        log.info("[REGRESSION 5 SUCCESS] Database entity persistence and decryption across restarts verified.");
    }

    @Test
    @DisplayName("Regression 6: Tamper detection & AEAD authentication rejection on previous-implementation ciphertext")
    void test6_TamperDetectionOnPreviousImplementationCiphertext() throws Exception {
        CryptoService modernService = new CryptoService(PREVIOUS_IMPL_KEY);
        String legacyCiphertext = generateCiphertextWithPreviousImplementation(PREVIOUS_IMPL_KEY, "TamperTestRecord");

        // Tamper with the base64 payload (flip last character)
        String payload = legacyCiphertext.substring(CryptoService.ENCRYPTION_PREFIX.length());
        char lastChar = payload.charAt(payload.length() - 1);
        char alteredChar = (lastChar == 'A') ? 'B' : 'A';
        String tamperedCiphertext = CryptoService.ENCRYPTION_PREFIX + payload.substring(0, payload.length() - 1) + alteredChar;

        assertThrows(SecurityException.class, () -> modernService.decrypt(tamperedCiphertext),
                "Tampered legacy ciphertext must fail GCM authentication and throw SecurityException");
        log.info("[REGRESSION 6 SUCCESS] AEAD tamper detection on legacy ciphertext verified.");
    }
